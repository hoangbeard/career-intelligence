#!/usr/bin/env node
// Builds <data>/INDEX.md and <data>/index.json from every job metadata.yml and
// company profile in the data root.
//
//   node scripts/build-index.mjs            write both files
//   node scripts/build-index.mjs --check    exit 1 if the files are stale; no writes
//   node scripts/build-index.mjs --out DIR  write to DIR instead of the data root
import { existsSync } from "node:fs";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { parseFrontMatter } from "./lib/flat-yaml.mjs";
import { loadJobs } from "./lib/jobs.mjs";
import { resolveDataRoot } from "./lib/paths.mjs";

export const STATUS_ORDER = [
  "interviewing",
  "offer",
  "applied",
  "watching",
  "analyzed",
  "new",
  "accepted",
  "declined",
  "rejected",
  "skipped",
];

async function loadCompanies(dataRoot) {
  const dir = join(dataRoot, "companies");
  if (!existsSync(dir)) return [];
  const rows = [];
  for (const slug of (await readdir(dir)).sort()) {
    const path = join(dir, slug, "profile.md");
    if (!existsSync(path)) continue;
    const meta = parseFrontMatter(await readFile(path, "utf8"));
    rows.push({ slug, name: meta.company ?? slug, path: `companies/${slug}/profile.md` });
  }
  return rows;
}

const fmt = (v) => (v == null || v === "" ? "—" : Array.isArray(v) ? v.join(", ") : String(v));
// Table cells must not break the Markdown table.
const cell = (v) => fmt(v).replace(/\|/g, "\\|").replace(/\n/g, " ");

export function renderIndex(jobs, companies, generatedOn) {
  let md = `# Job search index

> Generated by \`node scripts/build-index.mjs\`. Do not edit by hand.
> Updated: ${generatedOn} · ${jobs.length} jobs · ${companies.length} companies

## Jobs by status
`;
  for (const status of STATUS_ORDER) {
    const rows = jobs.filter((j) => j.status === status);
    if (!rows.length) continue;
    md += `\n### ${status} (${rows.length})\n\n`;
    md += "| ID | Name | Role | Company | Match | Career | Recommendation | Domains | Report |\n";
    md += "|---|---|---|---|---:|---:|---|---|---|\n";
    for (const j of rows) {
      const report = j.report ? `[report](${j.report})` : "—";
      md += `| \`${j.id}\` | [\`${j.name}\`](${j._path}) | ${cell(j.role)} | ${cell(j.company)} | ${cell(j.match_score)} | ${cell(j.career_score)} | ${cell(j.recommendation)} | ${cell(j.domains)} | ${report} |\n`;
    }
  }
  const unknown = jobs.filter((j) => !STATUS_ORDER.includes(j.status));
  if (unknown.length) {
    md += `\n### unknown status (${unknown.length}): fix metadata\n\n`;
    for (const j of unknown) md += `- ${j._path} (status: ${fmt(j.status)})\n`;
  }

  md += "\n## Companies\n\n| Company | Profile | Jobs |\n|---|---|---:|\n";
  for (const c of companies) {
    const n = jobs.filter((j) => j.company_slug === c.slug).length;
    md += `| ${cell(c.name)} | [profile](${c.path}) | ${n} |\n`;
  }

  const byDomain = new Map();
  for (const j of jobs) for (const d of j.domains ?? []) byDomain.set(d, [...(byDomain.get(d) ?? []), j]);
  if (byDomain.size) {
    md += "\n## Jobs by domain\n\n";
    for (const [d, list] of [...byDomain.entries()].sort()) {
      md += `- **${d}** (${list.length}): ${list.map((j) => `[\`${j.id}\` ${fmt(j.role)} @ ${fmt(j.company)}](${j._path})`).join(" · ")}\n`;
    }
  }

  const indexJobs = [...jobs]
    .sort((a, b) => a.id.localeCompare(b.id))
    .map(({ _path, eng_grc_ratio, ...meta }) => ({
      ...meta,
      // Schema v4 called the role mix `eng_grc_ratio`.
      role_mix: meta.role_mix ?? eng_grc_ratio ?? null,
      recommendation: meta.recommendation ?? null,
      status_changed_at: meta.status_changed_at ?? null,
      last_checked_at: meta.last_checked_at ?? null,
      source_urls: meta.source_urls ?? [],
      domains: meta.domains ?? [],
      id_year: Number(meta.id.slice(4, 8)),
      path: _path,
      metadata_path: `${_path}/metadata.yml`,
    }));
  const json = `${JSON.stringify(
    {
      schema_version: 2,
      generated_on: generatedOn,
      job_count: indexJobs.length,
      company_count: companies.length,
      jobs: indexJobs,
      companies,
    },
    null,
    2,
  )}\n`;
  return { "INDEX.md": md, "index.json": json };
}

// The date stamp changes daily; ignore it when checking for drift.
const stripDate = (text) =>
  text
    .replace(/^> Updated: \d{4}-\d{2}-\d{2} /m, "> Updated: <date> ")
    .replace(/^(\s*"generated_on":\s*)"\d{4}-\d{2}-\d{2}"/m, '$1"<date>"');

async function main(argv) {
  const dataRoot = resolveDataRoot();
  const outFlag = argv.indexOf("--out");
  const outDir = outFlag >= 0 ? resolve(argv[outFlag + 1] ?? "") : dataRoot;
  const jobs = await loadJobs(dataRoot);
  const companies = await loadCompanies(dataRoot);
  const outputs = renderIndex(jobs, companies, new Date().toISOString().slice(0, 10));

  if (argv.includes("--check")) {
    const stale = [];
    for (const [name, expected] of Object.entries(outputs)) {
      const path = join(outDir, name);
      if (!existsSync(path)) stale.push(`${name}: missing`);
      else if (stripDate(await readFile(path, "utf8")) !== stripDate(expected)) stale.push(`${name}: out of date`);
    }
    if (stale.length) {
      console.error(`Index is stale:\n  ${stale.join("\n  ")}\nRun: node scripts/build-index.mjs`);
      return 1;
    }
    console.log(`Index is current: ${jobs.length} jobs, ${companies.length} companies`);
    return 0;
  }

  await mkdir(outDir, { recursive: true });
  for (const [name, text] of Object.entries(outputs)) await writeFile(join(outDir, name), text);
  console.log(`Wrote INDEX.md and index.json to ${outDir}: ${jobs.length} jobs, ${companies.length} companies`);
  return 0;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    process.exitCode = await main(process.argv.slice(2));
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
