#!/usr/bin/env node
// Generates thin harness wrappers from skills/*.md front matter.
// skills/ stays the only place with workflow content.
//
//   node scripts/sync-wrappers.mjs           write wrappers
//   node scripts/sync-wrappers.mjs --check   exit 1 if any wrapper is missing, stale or orphaned
//
// Targets:
//   .claude/skills/<name>/SKILL.md   Claude Code
//   .agents/skills/<name>/SKILL.md   Codex, Cursor, Kilo
//   .omp/skills/<name>/SKILL.md      Oh My Pi
//   CLAUDE.md                        Claude Code reads CLAUDE.md, not AGENTS.md
//   kilo.jsonc                       Kilo project instructions
import { existsSync } from "node:fs";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { pathToFileURL } from "node:url";
import { parseFrontMatter } from "./lib/flat-yaml.mjs";
import { repoRoot } from "./lib/paths.mjs";

export const SKILL_DIRS = [".claude/skills", ".agents/skills", ".omp/skills"];
const NAME = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const HEADER = "<!-- Generated by scripts/sync-wrappers.mjs from skills/. Do not edit. -->";

export async function loadSkills(root = repoRoot) {
  const dir = join(root, "skills");
  const skills = [];
  for (const file of (await readdir(dir)).filter((f) => f.endsWith(".md")).sort()) {
    const meta = parseFrontMatter(await readFile(join(dir, file), "utf8"));
    const expected = file.slice(0, -3);
    if (meta.name !== expected) throw new Error(`skills/${file}: front matter name must be "${expected}"`);
    if (!NAME.test(meta.name)) throw new Error(`skills/${file}: name must be lowercase words joined by hyphens`);
    if (!meta.description || meta.description.length > 1024) {
      throw new Error(`skills/${file}: description is required (at most 1024 characters)`);
    }
    skills.push({ name: meta.name, description: meta.description });
  }
  return skills;
}

export function renderWrappers(skills) {
  const files = {};
  for (const { name, description } of skills) {
    const body =
      `---\nname: ${name}\ndescription: ${JSON.stringify(description)}\n---\n\n${HEADER}\n\n` +
      `Read and follow \`skills/${name}.md\` at the repository root.\n` +
      "Shared rules, the data root and commands are in `AGENTS.md`.\n";
    for (const dir of SKILL_DIRS) files[`${dir}/${name}/SKILL.md`] = body;
  }
  files["CLAUDE.md"] =
    `${HEADER}\n\n# rexcareer\n\n@AGENTS.md\n\n` +
    "Workflows live in `skills/`. Wrappers in `.claude/skills/` only point to them.\n";
  files["kilo.jsonc"] =
    "// Generated by scripts/sync-wrappers.mjs. Do not edit.\n" +
    `${JSON.stringify({ instructions: ["AGENTS.md"] }, null, 2)}\n`;
  return files;
}

// Wrapper folders whose skill no longer exists.
async function orphans(root, skills) {
  const names = new Set(skills.map((s) => s.name));
  const found = [];
  for (const dir of SKILL_DIRS) {
    const path = join(root, dir);
    if (!existsSync(path)) continue;
    for (const entry of await readdir(path)) if (!names.has(entry)) found.push(`${dir}/${entry}`);
  }
  return found;
}

export async function sync(root = repoRoot, { check = false } = {}) {
  const skills = await loadSkills(root);
  const files = renderWrappers(skills);
  const problems = [];
  for (const [rel, text] of Object.entries(files)) {
    const path = join(root, rel);
    const current = existsSync(path) ? await readFile(path, "utf8") : null;
    if (current === text) continue;
    if (check) problems.push(`${rel}: ${current === null ? "missing" : "out of date"}`);
    else {
      await mkdir(dirname(path), { recursive: true });
      await writeFile(path, text);
    }
  }
  for (const rel of await orphans(root, skills)) {
    if (check) problems.push(`${rel}: no matching skill`);
    else await rm(join(root, rel), { recursive: true });
  }
  return { skills, problems };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const check = process.argv.includes("--check");
    const { skills, problems } = await sync(repoRoot, { check });
    if (problems.length) {
      console.error(`Wrappers are stale:\n  ${problems.join("\n  ")}\nRun: node scripts/sync-wrappers.mjs`);
      process.exitCode = 1;
    } else {
      console.log(`${check ? "Wrappers are current" : "Wrote wrappers"}: ${skills.length} skills x ${SKILL_DIRS.length} harness folders`);
    }
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
