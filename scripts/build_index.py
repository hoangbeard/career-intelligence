#!/usr/bin/env python3
"""Builds <data>/INDEX.md and <data>/index.json from every job metadata.yml and
company profile in the data root.

  python3 scripts/build_index.py            write both files
  python3 scripts/build_index.py --check    exit 1 if the files are stale; no writes
  python3 scripts/build_index.py --out DIR  write to DIR instead of the data root
"""

from __future__ import annotations

import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

from lib.flat_yaml import parse_front_matter
from lib.jobs import load_jobs
from lib.paths import resolve_data_root

STATUS_ORDER = [
    "interviewing",
    "offer",
    "applied",
    "watching",
    "analyzed",
    "new",
    "accepted",
    "declined",
    "rejected",
    "skipped",
]


def load_companies(data_root: Path) -> list[dict]:
    directory = data_root / "companies"
    if not directory.exists():
        return []
    rows = []
    for slug in sorted(p.name for p in directory.iterdir()):
        path = directory / slug / "profile.md"
        if not path.exists():
            continue
        meta = parse_front_matter(path.read_text(encoding="utf-8"))
        name = meta.get("company")
        rows.append({"slug": slug, "name": slug if name is None else name, "path": f"companies/{slug}/profile.md"})
    return rows


def fmt(value) -> str:
    if value is None or value == "":
        return "—"
    if isinstance(value, list):
        return ", ".join(fmt_item(v) for v in value)
    return fmt_item(value)


def fmt_item(value) -> str:
    # Same text as JavaScript's String(): null -> "null", true -> "true".
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, list):
        return ",".join(fmt_item(v) for v in value)
    return str(value)


def cell(value) -> str:
    """Table cells must not break the Markdown table."""
    return fmt(value).replace("|", "\\|").replace("\n", " ")


def render_index(jobs: list[dict], companies: list[dict], generated_on: str) -> dict[str, str]:
    md = (
        "# Job search index\n\n"
        "> Generated by `python3 scripts/build_index.py`. Do not edit by hand.\n"
        f"> Updated: {generated_on} · {len(jobs)} jobs · {len(companies)} companies\n\n"
        "## Jobs by status\n"
    )
    for status in STATUS_ORDER:
        rows = [j for j in jobs if j.get("status") == status]
        if not rows:
            continue
        md += f"\n### {status} ({len(rows)})\n\n"
        md += "| ID | Name | Role | Company | Match | Career | Recommendation | Domains | Report |\n"
        md += "|---|---|---|---|---:|---:|---|---|---|\n"
        for j in rows:
            report = f"[report]({j['report']})" if j.get("report") else "—"
            md += (
                f"| `{j['id']}` | [`{j['name']}`]({j['_path']}) | {cell(j.get('role'))} | {cell(j.get('company'))} "
                f"| {cell(j.get('match_score'))} | {cell(j.get('career_score'))} | {cell(j.get('recommendation'))} "
                f"| {cell(j.get('domains'))} | {report} |\n"
            )
    unknown = [j for j in jobs if j.get("status") not in STATUS_ORDER]
    if unknown:
        md += f"\n### unknown status ({len(unknown)}): fix metadata\n\n"
        for j in unknown:
            md += f"- {j['_path']} (status: {fmt(j.get('status'))})\n"

    md += "\n## Companies\n\n| Company | Profile | Jobs |\n|---|---|---:|\n"
    for c in companies:
        n = sum(1 for j in jobs if j.get("company_slug") == c["slug"])
        md += f"| {cell(c['name'])} | [profile]({c['path']}) | {n} |\n"

    by_domain: dict[str, list[dict]] = {}
    for j in jobs:
        for d in j.get("domains") or []:
            by_domain.setdefault(d, []).append(j)
    if by_domain:
        md += "\n## Jobs by domain\n\n"
        # The original sorted "<domain>,<…>" strings; the comma keeps the same order.
        for d in sorted(by_domain, key=lambda d: f"{d},"):
            items = by_domain[d]
            links = " · ".join(f"[`{j['id']}` {fmt(j.get('role'))} @ {fmt(j.get('company'))}]({j['_path']})" for j in items)
            md += f"- **{d}** ({len(items)}): {links}\n"

    index_jobs = []
    for job in sorted(jobs, key=lambda j: j["id"]):
        meta = {k: v for k, v in job.items() if k not in ("_path", "eng_grc_ratio")}
        role_mix = job.get("role_mix")
        if role_mix is None:
            # Schema v4 called the role mix `eng_grc_ratio`.
            role_mix = job.get("eng_grc_ratio")
        meta["role_mix"] = role_mix
        for key in ("recommendation", "status_changed_at", "last_checked_at"):
            meta[key] = job.get(key)
        for key in ("source_urls", "domains"):
            meta[key] = [] if job.get(key) is None else job[key]
        meta["id_year"] = int(job["id"][4:8])
        meta["path"] = job["_path"]
        meta["metadata_path"] = f"{job['_path']}/metadata.yml"
        index_jobs.append(meta)
    data = {
        "schema_version": 2,
        "generated_on": generated_on,
        "job_count": len(index_jobs),
        "company_count": len(companies),
        "jobs": index_jobs,
        "companies": companies,
    }
    return {"INDEX.md": md, "index.json": json.dumps(data, ensure_ascii=False, indent=2) + "\n"}


def strip_date(text: str) -> str:
    """The date stamp changes daily; ignore it when checking for drift."""
    text = re.sub(r"^> Updated: \d{4}-\d{2}-\d{2} ", "> Updated: <date> ", text, count=1, flags=re.M)
    return re.sub(r'^(\s*"generated_on":\s*)"\d{4}-\d{2}-\d{2}"', r'\1"<date>"', text, count=1, flags=re.M)


def today_utc() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%d")


def main(argv: list[str]) -> int:
    data_root = resolve_data_root()
    out_dir = data_root
    if "--out" in argv:
        i = argv.index("--out")
        out_dir = Path(argv[i + 1] if i + 1 < len(argv) else "").resolve()
    jobs = load_jobs(data_root)
    companies = load_companies(data_root)
    outputs = render_index(jobs, companies, today_utc())

    if "--check" in argv:
        stale = []
        for name, expected in outputs.items():
            path = out_dir / name
            if not path.exists():
                stale.append(f"{name}: missing")
            elif strip_date(path.read_text(encoding="utf-8")) != strip_date(expected):
                stale.append(f"{name}: out of date")
        if stale:
            print("Index is stale:\n  " + "\n  ".join(stale) + "\nRun: python3 scripts/build_index.py", file=sys.stderr)
            return 1
        print(f"Index is current: {len(jobs)} jobs, {len(companies)} companies")
        return 0

    # Leave files alone when only the date would change: fewer merge conflicts
    # between sessions that save on different days.
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name, text in outputs.items():
        path = out_dir / name
        if path.exists() and strip_date(path.read_text(encoding="utf-8")) == strip_date(text):
            continue
        path.write_text(text, encoding="utf-8", newline="")
        written.append(name)
    summary = f"Wrote {' and '.join(written)}" if written else "Index unchanged"
    print(f"{summary} in {out_dir}: {len(jobs)} jobs, {len(companies)} companies")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except (RuntimeError, ValueError, OSError) as error:
        print(error, file=sys.stderr)
        sys.exit(1)
