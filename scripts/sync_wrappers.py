#!/usr/bin/env python3
"""Generates thin harness wrappers from skills/*.md front matter.
skills/ stays the only place with workflow content.

  python3 scripts/sync_wrappers.py           write wrappers
  python3 scripts/sync_wrappers.py --check   exit 1 if any wrapper is missing, stale or orphaned

Targets:
  .claude/skills/<name>/SKILL.md   Claude Code
  .agents/skills/<name>/SKILL.md   Codex, Cursor, Kilo
  .omp/skills/<name>/SKILL.md      Oh My Pi
  CLAUDE.md                        Claude Code reads CLAUDE.md, not AGENTS.md
  kilo.jsonc                       Kilo project instructions
"""

from __future__ import annotations

import json
import re
import shutil
import sys
from pathlib import Path

from lib.flat_yaml import parse_front_matter
from lib.paths import REPO_ROOT

SKILL_DIRS = [".claude/skills", ".agents/skills", ".omp/skills"]
NAME = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*")
HEADER = "<!-- Generated by scripts/sync_wrappers.py from skills/. Do not edit. -->"


def load_skills(root: Path = REPO_ROOT) -> list[dict]:
    skills = []
    for path in sorted((root / "skills").glob("*.md")):
        meta = parse_front_matter(path.read_text(encoding="utf-8"))
        expected = path.stem
        if meta.get("name") != expected:
            raise ValueError(f'skills/{path.name}: front matter name must be "{expected}"')
        if not NAME.fullmatch(expected):
            raise ValueError(f"skills/{path.name}: name must be lowercase words joined by hyphens")
        description = meta.get("description")
        if not description or len(description) > 1024:
            raise ValueError(f"skills/{path.name}: description is required (at most 1024 characters)")
        skills.append({"name": expected, "description": description})
    return skills


def render_wrappers(skills: list[dict]) -> dict[str, str]:
    files = {}
    for skill in skills:
        name = skill["name"]
        body = (
            f"---\nname: {name}\ndescription: {json.dumps(skill['description'], ensure_ascii=False)}\n---\n\n"
            f"{HEADER}\n\n"
            f"Read and follow `skills/{name}.md` at the repository root.\n"
            "Shared rules, the data root and commands are in `AGENTS.md`.\n"
        )
        for directory in SKILL_DIRS:
            files[f"{directory}/{name}/SKILL.md"] = body
    files["CLAUDE.md"] = (
        f"{HEADER}\n\n# career-intelligence\n\n@AGENTS.md\n\n"
        "Workflows live in `skills/`. Wrappers in `.claude/skills/` only point to them.\n"
    )
    files["kilo.jsonc"] = (
        "// Generated by scripts/sync_wrappers.py. Do not edit.\n"
        + json.dumps({"instructions": ["AGENTS.md"]}, indent=2)
        + "\n"
    )
    return files


def orphans(root: Path, skills: list[dict]) -> list[str]:
    """Wrapper folders whose skill no longer exists."""
    names = {s["name"] for s in skills}
    found = []
    for directory in SKILL_DIRS:
        path = root / directory
        if path.exists():
            found.extend(f"{directory}/{entry.name}" for entry in sorted(path.iterdir()) if entry.name not in names)
    return found


def sync(root: Path = REPO_ROOT, check: bool = False) -> tuple[list[dict], list[str]]:
    skills = load_skills(root)
    problems = []
    for rel, text in render_wrappers(skills).items():
        path = root / rel
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if check:
            problems.append(f"{rel}: {'missing' if current is None else 'out of date'}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="")
    for rel in orphans(root, skills):
        if check:
            problems.append(f"{rel}: no matching skill")
        else:
            shutil.rmtree(root / rel)
    return skills, problems


if __name__ == "__main__":
    check = "--check" in sys.argv
    try:
        skills, problems = sync(REPO_ROOT, check=check)
    except (ValueError, OSError) as error:
        print(error, file=sys.stderr)
        sys.exit(1)
    if problems:
        print("Wrappers are stale:\n  " + "\n  ".join(problems) + "\nRun: python3 scripts/sync_wrappers.py", file=sys.stderr)
        sys.exit(1)
    print(f"{'Wrappers are current' if check else 'Wrote wrappers'}: {len(skills)} skills x {len(SKILL_DIRS)} harness folders")
